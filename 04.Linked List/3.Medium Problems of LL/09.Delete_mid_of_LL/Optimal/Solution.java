/*
QUESTION:-
You are given the head of a linked list. Delete the middle node, and return the head of the modified linked list.

Example:
Input: head = [1,3,4,7,1,2,6]
Output: [1,3,4,1,2,6]
Explanation: Node 7 at index 3 is removed.
*/

/*
APPROACH:-
Fast and Slow Pointers: Start fast two steps ahead (fast = head.next.next) and slow at head. When fast reaches the end, slow is just before the middle node. Set slow.next = slow.next.next.
*/

import java.util.*;
import java.io.*;

// HELPER DEFINITION:-
class ListNode {
    int val;
    ListNode next;
    ListNode() {}
    ListNode(int val) { this.val = val; }
    ListNode(int val, ListNode next) { this.val = val; this.next = next; }
}

// CODE:-
class Solution {
    public ListNode deleteMiddle(ListNode head) {
        if (head == null || head.next == null) return null;
        ListNode slow = head, fast = head.next.next;
        while (fast != null && fast.next != null) {
            slow = slow.next;
            fast = fast.next.next;
        }
        slow.next = slow.next.next;
        return head;
    }
}

// TIME COMPLEXITY = O(N/2) = O(N)
// SPACE COMPLEXITY = O(1)
